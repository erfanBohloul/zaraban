"""Automated Regression Test Generator for Zaraban (Section 3.3).

Adds minimized crashing inputs automatically to the project's regression test suite:
"ورودی کوچک‌شده باید خودکار به مجموعۀ آزمون‌های رگرسیون پروژه اضافه شود
تا در اجراهای بعدی پایپ‌لاین بررسی گردد. آزمون باید خطای مورد انتظار را روی
نسخۀ پایه آشکار کند و نبود همان خطا و رفتار مورد انتظار را روی نسخۀ وصله‌شده بررسی کند."
"""

from __future__ import annotations
from dataclasses import dataclass, asdict
from pathlib import Path
from typing import Any, Optional


@dataclass
class RegressionTestResult:
    test_name: str
    input_file: str
    base_reveals_bug: bool
    patch_prevents_bug: bool
    is_valid_regression_test: bool
    details: str

    def to_dict(self) -> dict[str, Any]:
        return asdict(self)


class RegressionGenerator:
    """Manages the creation and verification of automated regression tests."""

    @classmethod
    def generate_regression_test(
        cls,
        output_dir: str | Path,
        target_name: str,
        original_test_name: str,
        minimized_bytes: bytes,
        error_type: str
    ) -> tuple[Path, dict[str, Any]]:
        """Generate regression test file and corresponding test definition dict."""
        reg_dir = Path(output_dir) / "regression_suite"
        reg_dir.mkdir(parents=True, exist_ok=True)

        reg_test_name = f"regression_{target_name}_{original_test_name}"
        input_filename = f"{reg_test_name}.txt"
        input_path = reg_dir / input_filename
        input_path.write_bytes(minimized_bytes)

        test_def = {
            "name": reg_test_name,
            "input_file": str(input_path.relative_to(Path(output_dir))),
            "description": f"Automated regression test generated by Zaraban for {error_type} in {original_test_name}",
            "expected_exit_code": 0
        }

        return input_path, test_def
